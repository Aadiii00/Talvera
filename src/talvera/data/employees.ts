import type { Employee, RiskPoint } from "./types";

// Deterministic 90-day trajectory: linear drift from `start` to `end` with a
// small fixed-phase sine ripple so the line looks organic without randomness.
function buildRiskHistory(start: number, end: number, rippleAmplitude = 3): RiskPoint[] {
  const points: RiskPoint[] = [];
  for (let day = 0; day <= 90; day += 5) {
    const t = day / 90;
    const drift = start + (end - start) * t;
    const ripple = Math.sin(day / 9) * rippleAmplitude;
    const risk = Math.max(0, Math.min(100, Math.round(drift + ripple)));
    points.push({ day, risk });
  }
  return points;
}

